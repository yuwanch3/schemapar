/**
 * schemapar — TypeScript validator codegen
 *
 * Generates a self-contained, dependency-free TypeScript module that exports
 * `validate(value): ValidationError[]`. An empty array means the value is valid.
 *
 * Design goals:
 *  - Output is readable, so users can vendor it into their repo.
 *  - No imports, no `any` in generated logic (only at the boundary).
 *  - Every check reports the same error path structure as the Python validator
 *    so that parity is a structural, not textual, comparison.
 *
 * Control-flow note: child nodes are validated inside `if / else` branches
 * rather than with early `return`s. A `return` would leave the enclosing
 * `walk()` call entirely, silently skipping sibling properties and the rest of
 * an array. Guards therefore only skip the node they belong to.
 */

import type { SchemaNode, CrossFieldConstraint } from './schema.js';
import { FORMAT_PATTERNS } from './schema.js';
import type { StringFormat } from './schema.js';

export interface GenTsOptions {
  /** Name of the exported validator function. Default: `validate`. */
  readonly functionName?: string;
  /** Emit a `type` alias describing the validated shape. Default: true. */
  readonly emitType?: boolean;
  /** Add a header comment. Default: true. */
  readonly header?: boolean;
}

interface Ctx {
  readonly lines: string[];
  readonly varCounter: { n: number };
  /**
   * Module-level helper functions collected while emitting. Currently used
   * by union variants, which must be isolated so that a `return` in one
   * variant does not abort validation of the others.
   */
  readonly helpers: string[];
  /** Shared flags for helpers that are emitted at most once. */
  readonly flags: { codePointSort: boolean };
}

const INDENT = '  ';

function push(ctx: Ctx, depth: number, line: string): void {
  ctx.lines.push(INDENT.repeat(depth) + line);
}

function nextVar(ctx: Ctx, prefix: string): string {
  ctx.varCounter.n += 1;
  return `${prefix}${ctx.varCounter.n}`;
}

/** Escape a string as a TS string literal. */
function tsString(s: string): string {
  return JSON.stringify(s);
}

function tsLiteral(value: string | number | boolean | null): string {
  if (value === null) return 'null';
  if (typeof value === 'string') return tsString(value);
  return String(value);
}

/** Render a `path` array literal as a TS expression. */
function pathExpr(parts: ReadonlyArray<string | number>): string {
  const items = parts.map((p) => (typeof p === 'number' ? String(p) : tsString(p)));
  return `[${items.join(', ')}]`;
}

export function generateTypeScript(root: SchemaNode, options: GenTsOptions = {}): string {
  const fn = options.functionName ?? 'validate';
  const emitType = options.emitType ?? true;
  const header = options.header ?? true;

  const ctx: Ctx = { lines: [], varCounter: { n: 0 }, helpers: [], flags: { codePointSort: false } };

  if (header) {
    ctx.lines.push('/**');
    ctx.lines.push(' * AUTO-GENERATED by schemapar. Do not edit by hand.');
    ctx.lines.push(' * Run `schemapar compile <schema> --target ts` to regenerate.');
    ctx.lines.push(' */');
    ctx.lines.push('');
  }

  ctx.lines.push('export interface ValidationError {');
  ctx.lines.push('  readonly path: ReadonlyArray<string | number>;');
  ctx.lines.push('  readonly message: string;');
  ctx.lines.push('}');
  ctx.lines.push('');

  if (emitType) {
    ctx.lines.push('export type Infer = ' + renderType(root, 0) + ';');
    ctx.lines.push('');
  }

  ctx.lines.push(`export function ${fn}(value: unknown): ValidationError[] {`);
  push(ctx, 1, 'const errors: ValidationError[] = [];');
  push(ctx, 1, 'walk(value, [], errors);');
  push(ctx, 1, 'return errors;');
  ctx.lines.push('}');
  ctx.lines.push('');

  // Emit the recursive walker. The walker is a plain function so the
  // generated module stays at the top level (no closures over user state).
  ctx.lines.push('function walk(value: unknown, path: ReadonlyArray<string | number>, errors: ValidationError[]): void {');
  emitNode(ctx, root, 'value', 'path', 'errors', 1);
  ctx.lines.push('}');
  ctx.lines.push('');

  // Helpers (union variants) must be appended after `walk` so they can be
  // referenced from inside it regardless of declaration order. TS/JS hoist
  // function declarations, so forward references are fine.
  if (ctx.flags.codePointSort) {
    ctx.lines.push('/** Sort strings by Unicode code point, matching Python\'s `sorted()`.');
    ctx.lines.push(' * Plain `Array#sort()` compares UTF-16 code units, so astral');
    ctx.lines.push(' * characters (emoji) would be ordered differently in JS.');
    ctx.lines.push(' */');
    ctx.lines.push('function _byCodePoint(a: string, b: string): number {');
    ctx.lines.push('  const ac = Array.from(a);');
    ctx.lines.push('  const bc = Array.from(b);');
    ctx.lines.push('  const n = Math.min(ac.length, bc.length);');
    ctx.lines.push('  for (let i = 0; i < n; i++) {');
    ctx.lines.push('    const diff = ac[i]!.codePointAt(0)! - bc[i]!.codePointAt(0)!;');
    ctx.lines.push('    if (diff !== 0) return diff;');
    ctx.lines.push('  }');
    ctx.lines.push('  return ac.length - bc.length;');
    ctx.lines.push('}');
    ctx.lines.push('');
  }

  for (const h of ctx.helpers) {
    ctx.lines.push(h);
    ctx.lines.push('');
  }

  return ctx.lines.join('\n');
}

// ---------------------------------------------------------------------------
// Scoped emission helpers
// ---------------------------------------------------------------------------

/** Emit into a fresh relative-depth buffer so it can be nested/indented. */
function capture(ctx: Ctx, body: (sub: Ctx) => void): string[] {
  const sub: Ctx = { lines: [], varCounter: ctx.varCounter, helpers: ctx.helpers, flags: ctx.flags };
  body(sub);
  return sub.lines;
}

function emitLines(ctx: Ctx, depth: number, lines: ReadonlyArray<string>): void {
  for (const line of lines) ctx.lines.push(INDENT.repeat(depth) + line);
}

/**
 * `if (failCond) { failLines } else { body }`
 *
 * The `else` branch is omitted when the node has no further checks, and the
 * whole construct is skipped when there is nothing to do either way.
 */
function emitGuard(
  ctx: Ctx,
  depth: number,
  failCond: string,
  failLines: ReadonlyArray<string>,
  body?: (sub: Ctx) => void,
): void {
  const bodyLines = body === undefined ? [] : capture(ctx, body);
  if (bodyLines.length === 0 && failLines.length === 0) return;
  push(ctx, depth, `if (${failCond}) {`);
  emitLines(ctx, depth + 1, failLines);
  if (bodyLines.length === 0) {
    push(ctx, depth, '}');
    return;
  }
  push(ctx, depth, '} else {');
  emitLines(ctx, depth + 1, bodyLines);
  push(ctx, depth, '}');
}

/**
 * `if (!(skipCond)) { body }`
 *
 * Used for `optional` / `nullable`: when the sentinel is present the node is
 * skipped, but the enclosing walk (siblings, arrays) continues.
 */
function emitSkip(ctx: Ctx, depth: number, skipCond: string, body: (sub: Ctx) => void): void {
  const bodyLines = capture(ctx, body);
  if (bodyLines.length === 0) return;
  push(ctx, depth, `if (!(${skipCond})) {`);
  emitLines(ctx, depth + 1, bodyLines);
  push(ctx, depth, '}');
}

function errLine(errorsVar: string, pathVar: string, message: string): string {
  return `${errorsVar}.push({ path: ${pathVar}, message: ${tsString(message)} });`;
}

// ---------------------------------------------------------------------------
// Node emission
// ---------------------------------------------------------------------------

/**
 * Emit statements that validate `valueExpr` at `pathExpr` against `node`.
 * Applicability modifiers are handled as nested guards; nothing here exits
 * the enclosing function, so sibling nodes are always visited.
 */
function emitNode(
  ctx: Ctx,
  node: SchemaNode,
  valueExpr: string,
  pathVar: string,
  errorsVar: string,
  depth: number,
): void {
  const body = (c: Ctx, d: number): void =>
    emitNodeBody(c, node, valueExpr, pathVar, errorsVar, d);

  const afterNullable = (c: Ctx, d: number): void => {
    if (node.nullable) {
      emitSkip(c, d, `${valueExpr} === null`, (sub) => body(sub, 0));
    } else {
      body(c, d);
    }
  };

  if (node.optional) {
    emitSkip(ctx, depth, `${valueExpr} === undefined`, (sub) => afterNullable(sub, 0));
  } else {
    afterNullable(ctx, depth);
  }
}

function emitNodeBody(
  ctx: Ctx,
  node: SchemaNode,
  valueExpr: string,
  pathVar: string,
  errorsVar: string,
  depth: number,
): void {
  switch (node.type) {
    case 'any': {
      // No constraint. Still reject `undefined` unless optional.
      if (!node.optional) {
        emitGuard(ctx, depth, `${valueExpr} === undefined`, [
          errLine(errorsVar, pathVar, 'expected a value, got undefined'),
        ]);
      }
      return;
    }

    case 'string': {
      emitGuard(
        ctx,
        depth,
        `typeof ${valueExpr} !== 'string'`,
        [errLine(errorsVar, pathVar, 'expected string')],
        (s) => {
          if (node.minLength !== undefined || node.maxLength !== undefined) {
            // Use code-point length to match Python's `len(str)`. Plain
            // `string.length` counts UTF-16 units and would diverge on emoji.
            push(s, 0, '{');
            push(s, 1, `const _cpLen = [...(${valueExpr} as string)].length;`);
            if (node.minLength !== undefined) {
              push(s, 1, `if (_cpLen < ${node.minLength}) {`);
              push(s, 2, errLine(errorsVar, pathVar, `string shorter than ${node.minLength}`));
              push(s, 1, '}');
            }
            if (node.maxLength !== undefined) {
              push(s, 1, `if (_cpLen > ${node.maxLength}) {`);
              push(s, 2, errLine(errorsVar, pathVar, `string longer than ${node.maxLength}`));
              push(s, 1, '}');
            }
            push(s, 0, '}');
          }
          if (node.pattern !== undefined) {
            const re = nextVar(s, 're');
            push(s, 0, `const ${re} = new RegExp(${tsString(node.pattern)});`);
            push(s, 0, `if (!${re}.test(${valueExpr})) {`);
            push(s, 1, errLine(errorsVar, pathVar, 'string does not match pattern'));
            push(s, 0, '}');
          }
          if (node.format !== undefined) {
            emitFormatCheck(s, node.format, valueExpr, pathVar, errorsVar, 0);
          }
        },
      );
      return;
    }

    case 'number': {
      emitGuard(
        ctx,
        depth,
        `typeof ${valueExpr} !== 'number' || !Number.isFinite(${valueExpr})`,
        [errLine(errorsVar, pathVar, 'expected number')],
        (s) => {
          if (node.min !== undefined) {
            push(s, 0, `if (${valueExpr} < ${node.min}) {`);
            push(s, 1, errLine(errorsVar, pathVar, `number less than ${node.min}`));
            push(s, 0, '}');
          }
          if (node.max !== undefined) {
            push(s, 0, `if (${valueExpr} > ${node.max}) {`);
            push(s, 1, errLine(errorsVar, pathVar, `number greater than ${node.max}`));
            push(s, 0, '}');
          }
        },
      );
      return;
    }

    case 'integer': {
      emitGuard(
        ctx,
        depth,
        `typeof ${valueExpr} !== 'number' || !Number.isInteger(${valueExpr})`,
        [errLine(errorsVar, pathVar, 'expected integer')],
        (s) => {
          if (node.min !== undefined) {
            push(s, 0, `if (${valueExpr} < ${node.min}) {`);
            push(s, 1, errLine(errorsVar, pathVar, `integer less than ${node.min}`));
            push(s, 0, '}');
          }
          if (node.max !== undefined) {
            push(s, 0, `if (${valueExpr} > ${node.max}) {`);
            push(s, 1, errLine(errorsVar, pathVar, `integer greater than ${node.max}`));
            push(s, 0, '}');
          }
        },
      );
      return;
    }

    case 'boolean': {
      emitGuard(ctx, depth, `typeof ${valueExpr} !== 'boolean'`, [
        errLine(errorsVar, pathVar, 'expected boolean'),
      ]);
      return;
    }

    case 'literal': {
      const message = `expected literal ${JSON.stringify(node.value)}`;
      emitGuard(ctx, depth, `${valueExpr} !== ${tsLiteral(node.value)}`, [
        errLine(errorsVar, pathVar, message),
      ]);
      return;
    }

    case 'enum': {
      const list = node.values.map((v) => tsLiteral(v)).join(', ');
      emitGuard(ctx, depth, `![${list}].includes(${valueExpr} as never)`, [
        errLine(errorsVar, pathVar, 'value not in enum'),
      ]);
      return;
    }

    case 'array': {
      emitGuard(
        ctx,
        depth,
        `!Array.isArray(${valueExpr})`,
        [errLine(errorsVar, pathVar, 'expected array')],
        (s) => {
          if (node.minItems !== undefined) {
            push(s, 0, `if (${valueExpr}.length < ${node.minItems}) {`);
            push(s, 1, errLine(errorsVar, pathVar, `array shorter than ${node.minItems}`));
            push(s, 0, '}');
          }
          if (node.maxItems !== undefined) {
            push(s, 0, `if (${valueExpr}.length > ${node.maxItems}) {`);
            push(s, 1, errLine(errorsVar, pathVar, `array longer than ${node.maxItems}`));
            push(s, 0, '}');
          }
          const idx = nextVar(s, 'i');
          push(s, 0, `for (let ${idx} = 0; ${idx} < ${valueExpr}.length; ${idx}++) {`);
          const itemPath = nextVar(s, 'p');
          push(s, 1, `const ${itemPath} = [...${pathVar}, ${idx}];`);
          const itemVal = nextVar(s, 'v');
          push(s, 1, `const ${itemVal} = (${valueExpr} as ReadonlyArray<unknown>)[${idx}];`);
          emitNode(s, node.items, itemVal, itemPath, errorsVar, 1);
          push(s, 0, '}');
        },
      );
      return;
    }

    case 'object': {
      emitGuard(
        ctx,
        depth,
        `typeof ${valueExpr} !== 'object' || ${valueExpr} === null || Array.isArray(${valueExpr})`,
        [errLine(errorsVar, pathVar, 'expected object')],
        (s) => {
          // Unique per object node: nested/sibling objects would otherwise
          // redeclare `const obj` in the same block (invalid TS).
          const objVar = nextVar(s, 'obj');
          push(s, 0, `const ${objVar} = ${valueExpr} as Record<string, unknown>;`);

          // Constraints only run when the object is structurally valid, so a
          // missing/mistyped property does not also produce constraint noise.
          const constraints = node.constraints;
          const hasConstraints = constraints !== undefined && constraints.length > 0;
          const errCountVar = hasConstraints ? nextVar(s, 'errCount') : '';
          if (hasConstraints) {
            push(s, 0, `const ${errCountVar} = ${errorsVar}.length;`);
          }

          const allowAdditional = node.additionalProperties ?? true;
          const knownKeys = Object.keys(node.properties);

          for (const key of knownKeys) {
            const child = node.properties[key]!;
            const childPath = nextVar(s, 'p');
            push(s, 0, `const ${childPath} = [...${pathVar}, ${tsString(key)}];`);
            const childVal = nextVar(s, 'v');
            push(s, 0, `const ${childVal} = ${objVar}[${tsString(key)}];`);
            emitNode(s, child, childVal, childPath, errorsVar, 0);
          }

          if (!allowAdditional) {
            const knownList = knownKeys.map((k) => tsString(k)).join(', ');
            // Sort keys so error order matches Python's sorted iteration.
            s.flags.codePointSort = true;
            push(s, 0, `for (const k of Object.keys(${objVar}).sort(_byCodePoint)) {`);
            push(s, 1, `if (![${knownList}].includes(k)) {`);
            push(s, 2, errLine(errorsVar, `[...${pathVar}, k]`, 'unexpected property'));
            push(s, 1, '}');
            push(s, 0, '}');
          }

          if (hasConstraints && constraints !== undefined) {
            push(s, 0, `if (${errorsVar}.length === ${errCountVar}) {`);
            emitConstraints(s, constraints, objVar, pathVar, errorsVar, 1);
            push(s, 0, '}');
          }
        },
      );
      return;
    }

    case 'record': {
      emitGuard(
        ctx,
        depth,
        `typeof ${valueExpr} !== 'object' || ${valueExpr} === null || Array.isArray(${valueExpr})`,
        [errLine(errorsVar, pathVar, 'expected object')],
        (s) => {
          const rec = nextVar(s, 'rec');
          const recKeys = nextVar(s, 'keys');
          push(s, 0, `const ${rec} = ${valueExpr} as Record<string, unknown>;`);
          s.flags.codePointSort = true;
          push(s, 0, `const ${recKeys} = Object.keys(${rec}).sort(_byCodePoint);`);
          if (node.minProperties !== undefined) {
            push(s, 0, `if (${recKeys}.length < ${node.minProperties}) {`);
            push(s, 1, errLine(errorsVar, pathVar, `object has fewer than ${node.minProperties} properties`));
            push(s, 0, '}');
          }
          if (node.maxProperties !== undefined) {
            push(s, 0, `if (${recKeys}.length > ${node.maxProperties}) {`);
            push(s, 1, errLine(errorsVar, pathVar, `object has more than ${node.maxProperties} properties`));
            push(s, 0, '}');
          }
          const rk = nextVar(s, 'rk');
          push(s, 0, `for (const ${rk} of ${recKeys}) {`);
          const rp = nextVar(s, 'p');
          push(s, 1, `const ${rp} = [...${pathVar}, ${rk}];`);
          const rv = nextVar(s, 'v');
          push(s, 1, `const ${rv} = ${rec}[${rk}];`);
          emitNode(s, node.values, rv, rp, errorsVar, 1);
          push(s, 0, '}');
        },
      );
      return;
    }

    case 'tuple': {
      emitGuard(
        ctx,
        depth,
        `!Array.isArray(${valueExpr})`,
        [errLine(errorsVar, pathVar, 'expected array')],
        (s) => {
          emitGuard(
            s,
            0,
            `${valueExpr}.length !== ${node.items.length}`,
            [errLine(errorsVar, pathVar, `tuple must have exactly ${node.items.length} items`)],
            (s2) => {
              const tVal = nextVar(s2, 't');
              push(s2, 0, `const ${tVal} = ${valueExpr} as ReadonlyArray<unknown>;`);
              node.items.forEach((item, i) => {
                const tp = nextVar(s2, 'p');
                push(s2, 0, `const ${tp} = [...${pathVar}, ${i}];`);
                const tv = nextVar(s2, 'v');
                push(s2, 0, `const ${tv} = ${tVal}[${i}];`);
                emitNode(s2, item, tv, tp, errorsVar, 0);
              });
            },
          );
        },
      );
      return;
    }

    case 'union': {
      // Semantics: a value is valid if it validates against ANY variant.
      //
      // Each variant is emitted as an ISOLATED helper function so that a
      // variant's own guards cannot affect sibling variants.
      const variantNames: string[] = [];
      for (const variant of node.variants) {
        const name = `_unionVariant${ctx.varCounter.n}`;
        ctx.varCounter.n += 1;
        const inner: Ctx = { lines: [], varCounter: ctx.varCounter, helpers: ctx.helpers, flags: ctx.flags };
        emitNode(inner, variant, 'value', 'path', 'errors', 1);
        ctx.helpers.push(
          `function ${name}(value: unknown, path: ReadonlyArray<string | number>, errors: ValidationError[]): void {\n` +
            inner.lines.join('\n') +
            '\n}',
        );
        variantNames.push(name);
      }

      const okVar = nextVar(ctx, 'u');
      push(ctx, depth, `let ${okVar}_ok = false;`);
      for (const name of variantNames) {
        const errsVar = nextVar(ctx, 'e');
        push(ctx, depth, `{`);
        push(ctx, depth + 1, `const ${errsVar}: ValidationError[] = [];`);
        push(ctx, depth + 1, `${name}(${valueExpr}, ${pathVar}, ${errsVar});`);
        push(ctx, depth + 1, `if (${errsVar}.length === 0) { ${okVar}_ok = true; }`);
        push(ctx, depth, `}`);
      }
      push(ctx, depth, `if (!${okVar}_ok) {`);
      push(ctx, depth + 1, errLine(errorsVar, pathVar, 'value matched no union variant'));
      push(ctx, depth, '}');
      return;
    }

    default: {
      const _never: never = node;
      void _never;
    }
  }
}

/**
 * Emit cross-field constraint checks. Runs AFTER structural validation so
 * that error paths and messages stay in lockstep with the Python generator.
 * `objVar` must be in scope and typed as `Record<string, unknown>`.
 */
function emitConstraints(
  ctx: Ctx,
  constraints: ReadonlyArray<CrossFieldConstraint>,
  objVar: string,
  pathVar: string,
  errorsVar: string,
  depth: number,
): void {
  for (const c of constraints) {
    if (c.kind === 'requiredTogether') {
      const fields = c.fields;
      const msg = c.message ?? `fields must be provided together: ${fields.join(', ')}`;
      // Count present fields; present iff value !== undefined.
      const presentVar = nextVar(ctx, 'present');
      push(ctx, depth, `{`);
      push(ctx, depth + 1, `let ${presentVar} = 0;`);
      for (const f of fields) {
        push(ctx, depth + 1, `if (${objVar}[${tsString(f)}] !== undefined) ${presentVar}++;`);
      }
      push(ctx, depth + 1, `if (${presentVar} > 0 && ${presentVar} < ${fields.length}) {`);
      push(ctx, depth + 2, errLine(errorsVar, pathVar, msg));
      push(ctx, depth + 1, '}');
      push(ctx, depth, '}');
      continue;
    }

    const op = comparisonOp(c.kind);
    const msg = c.message ?? `constraint failed: ${c.left} ${op.text} ${c.right}`;
    const lv = nextVar(ctx, 'l');
    const rv = nextVar(ctx, 'r');
    push(ctx, depth, `{`);
    push(ctx, depth + 1, `const ${lv} = ${objVar}[${tsString(c.left)}];`);
    push(ctx, depth + 1, `const ${rv} = ${objVar}[${tsString(c.right)}];`);
    if (c.kind === 'equal' || c.kind === 'notEqual') {
      // Strict equality is type-aware (mirrors Python `_eq_strict` and Go's
      // `strictEqual`). Absence on either side means the constraint is skipped.
      push(ctx, depth + 1, `if (${lv} !== undefined && ${rv} !== undefined) {`);
      const predicate = c.kind === 'equal' ? `${lv} === ${rv}` : `${lv} !== ${rv}`;
      push(ctx, depth + 2, `if (!(${predicate})) {`);
      push(ctx, depth + 3, errLine(errorsVar, pathVar, msg));
      push(ctx, depth + 2, '}');
      push(ctx, depth + 1, '}');
    } else {
      // Ordering constraints only apply when BOTH sides are finite numbers.
      // `Number.isFinite` mirrors Python's `math.isfinite` and Go's
      // `math.IsNaN/IsInf` checks, so NaN/Infinity are skipped in every
      // generated language.
      push(ctx, depth + 1, `if (typeof ${lv} === 'number' && typeof ${rv} === 'number' && Number.isFinite(${lv}) && Number.isFinite(${rv})) {`);
      push(ctx, depth + 2, `if (!(${lv} ${op.js} ${rv})) {`);
      push(ctx, depth + 3, errLine(errorsVar, pathVar, msg));
      push(ctx, depth + 2, '}');
      push(ctx, depth + 1, '}');
    }
    push(ctx, depth, '}');
  }
}

interface ComparisonOp {
  readonly js: string;
  readonly text: string;
  readonly py: string;
}

function comparisonOp(kind: Exclude<CrossFieldConstraint['kind'], 'requiredTogether'>): ComparisonOp {
  switch (kind) {
    case 'greaterThan':
      return { js: '>', text: '>', py: '>' };
    case 'lessThan':
      return { js: '<', text: '<', py: '<' };
    case 'greaterOrEqual':
      return { js: '>=', text: '>=', py: '>=' };
    case 'lessOrEqual':
      return { js: '<=', text: '<=', py: '<=' };
    case 'equal':
      return { js: '===', text: '==', py: '==' };
    case 'notEqual':
      return { js: '!==', text: '!=', py: '!=' };
  }
}

function emitFormatCheck(
  ctx: Ctx,
  format: StringFormat,
  valueExpr: string,
  pathVar: string,
  errorsVar: string,
  depth: number,
): void {
  const re = nextVar(ctx, 'fmt');
  // `new RegExp` keeps the shared source string verbatim, so the format is
  // defined exactly once in schema.ts.
  push(ctx, depth, `const ${re} = new RegExp(${JSON.stringify(FORMAT_PATTERNS[format])});`);
  push(ctx, depth, `if (!${re}.test(${valueExpr})) {`);
  push(ctx, depth + 1, errLine(errorsVar, pathVar, `string does not match format ${format}`));
  push(ctx, depth, '}');
}

/** Render a TS type describing a valid value. */
function renderType(node: SchemaNode, depth: number): string {
  let base: string;
  switch (node.type) {
    case 'any':
      base = 'unknown';
      break;
    case 'string':
      base = 'string';
      break;
    case 'number':
    case 'integer':
      base = 'number';
      break;
    case 'boolean':
      base = 'boolean';
      break;
    case 'literal':
      base = tsLiteral(node.value);
      break;
    case 'enum':
      base = node.values.map((v) => tsLiteral(v)).join(' | ');
      break;
    case 'array':
      base = `ReadonlyArray<${renderType(node.items, depth + 1)}>`;
      break;
    case 'record':
      base = `{ readonly [key: string]: ${renderType(node.values, depth + 1)} }`;
      break;
    case 'tuple': {
      const items = node.items.map((it) => renderType(it, depth + 1)).join(', ');
      base = `readonly [${items}]`;
      break;
    }
    case 'union':
      base = node.variants.map((v) => renderType(v, depth + 1)).join(' | ');
      break;
    case 'object': {
      const indent = INDENT.repeat(depth + 1);
      const closeIndent = INDENT.repeat(depth);
      const entries = Object.entries(node.properties).map(([k, v]) => {
        const optionalMark = v.optional ? '?' : '';
        return `${indent}readonly ${tsString(k)}${optionalMark}: ${renderType(v, depth + 1)};`;
      });
      base = entries.length === 0 ? 'Record<string, never>' : `{\n${entries.join('\n')}\n${closeIndent}}`;
      break;
    }
  }
  if (node.nullable) base = base + ' | null';
  return base;
}
