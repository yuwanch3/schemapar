/**
 * Emit statements that validate `valueExpr` at `pathVar` against `node`.
 * Applicability modifiers are handled as nested guards; nothing here exits
 * the enclosing function, so sibling nodes are always visited.
 */
function emitNode(
  ctx: Ctx,
  node: SchemaNode,
  valueExpr: string,
  pathVar: string,
  errorsVar: string,
  depth: number,
): void {
  const body = (c: Ctx, d: number): void =>
    emitNodeBody(c, node, valueExpr, pathVar, errorsVar, d);

  const afterNullable = (c: Ctx, d: number): void => {
    if (node.nullable) {
      emitSkip(c, d, `${valueExpr} is None`, (sub) => body(sub, 0));
    } else {
      body(c, d);
    }
  };

  if (node.optional) {
    emitSkip(ctx, depth, `${valueExpr} is _MISSING`, (sub) => afterNullable(sub, 0));
  } else {
    afterNullable(ctx, depth);
  }
}

function emitNodeBody(
  ctx: Ctx,
  node: SchemaNode,
  valueExpr: string,
  pathVar: string,
  errorsVar: string,
  depth: number,
): void {
  switch (node.type) {
    case 'any': {
      if (!node.optional) {
        emitGuard(ctx, depth, `${valueExpr} is _MISSING`, [
          errLine(errorsVar, pathVar, 'expected a value, got undefined'),
        ]);
      }
      return;
    }

    case 'string': {
      emitGuard(
        ctx,
        depth,
        `not isinstance(${valueExpr}, str)`,
        [errLine(errorsVar, pathVar, 'expected string')],
        (s) => {
          if (node.minLength !== undefined) {
            push(s, 0, `if len(${valueExpr}) < ${node.minLength}:`);
            push(s, 1, errLine(errorsVar, pathVar, `string shorter than ${node.minLength}`));
          }
          if (node.maxLength !== undefined) {
            push(s, 0, `if len(${valueExpr}) > ${node.maxLength}:`);
            push(s, 1, errLine(errorsVar, pathVar, `string longer than ${node.maxLength}`));
          }
          if (node.pattern !== undefined) {
            const re = nextVar(s, 're');
            push(s, 0, `${re} = re.compile(${pyString(translatePatternForPython(node.pattern))})`);
            push(s, 0, `if not ${re}.search(${valueExpr}):`);
            push(s, 1, errLine(errorsVar, pathVar, 'string does not match pattern'));
          }
          if (node.format !== undefined) {
            emitFormatCheck(s, node.format, valueExpr, pathVar, errorsVar, 0);
          }
        },
      );
      return;
    }

    case 'number': {
      emitGuard(
        ctx,
        depth,
        `not _is_number(${valueExpr})`,
        [errLine(errorsVar, pathVar, 'expected number')],
        (s) => {
          if (node.min !== undefined) {
            push(s, 0, `if ${valueExpr} < ${node.min}:`);
            push(s, 1, errLine(errorsVar, pathVar, `number less than ${node.min}`));
          }
          if (node.max !== undefined) {
            push(s, 0, `if ${valueExpr} > ${node.max}:`);
            push(s, 1, errLine(errorsVar, pathVar, `number greater than ${node.max}`));
          }
        },
      );
      return;
    }

    case 'integer': {
      emitGuard(
        ctx,
        depth,
        `not _is_integer(${valueExpr})`,
        [errLine(errorsVar, pathVar, 'expected integer')],
        (s) => {
          if (node.min !== undefined) {
            push(s, 0, `if ${valueExpr} < ${node.min}:`);
            push(s, 1, errLine(errorsVar, pathVar, `integer less than ${node.min}`));
          }
          if (node.max !== undefined) {
            push(s, 0, `if ${valueExpr} > ${node.max}:`);
            push(s, 1, errLine(errorsVar, pathVar, `integer greater than ${node.max}`));
          }
        },
      );
      return;
    }

    case 'boolean': {
      emitGuard(ctx, depth, `not isinstance(${valueExpr}, bool)`, [
        errLine(errorsVar, pathVar, 'expected boolean'),
      ]);
      return;
    }

    case 'literal': {
      emitGuard(ctx, depth, `not _eq_strict(${valueExpr}, ${pyValueLiteral(node.value)})`, [
        errLine(errorsVar, pathVar, literalMessage(node.value)),
      ]);
      return;
    }

    case 'enum': {
      const values = node.values.map((v) => pyValueLiteral(v)).join(', ');
      emitGuard(
        ctx,
        depth,
        `not any(_eq_strict(${valueExpr}, _v) for _v in (${values}))`,
        [errLine(errorsVar, pathVar, 'value not in enum')],
      );
      return;
    }

    case 'array': {
      emitGuard(
        ctx,
        depth,
        `not isinstance(${valueExpr}, list)`,
        [errLine(errorsVar, pathVar, 'expected array')],
        (s) => {
          if (node.minItems !== undefined) {
            push(s, 0, `if len(${valueExpr}) < ${node.minItems}:`);
            push(s, 1, errLine(errorsVar, pathVar, `array shorter than ${node.minItems}`));
          }
          if (node.maxItems !== undefined) {
            push(s, 0, `if len(${valueExpr}) > ${node.maxItems}:`);
            push(s, 1, errLine(errorsVar, pathVar, `array longer than ${node.maxItems}`));
          }
          const idx = nextVar(s, 'i');
          push(s, 0, `for ${idx} in range(len(${valueExpr})):`);
          const itemPath = nextVar(s, 'p');
          push(s, 1, `${itemPath} = ${pathVar} + [${idx}]`);
          const itemVal = nextVar(s, 'v');
          push(s, 1, `${itemVal} = ${valueExpr}[${idx}]`);
          emitNode(s, node.items, itemVal, itemPath, errorsVar, 1);
        },
      );
      return;
    }

    case 'object': {
      emitGuard(
        ctx,
        depth,
        `not isinstance(${valueExpr}, dict)`,
        [errLine(errorsVar, pathVar, 'expected object')],
        (s) => {
          // Constraints only run when the object is structurally valid, so a
          // missing/mistyped property does not also produce constraint noise.
          const constraints = node.constraints;
          const hasConstraints = constraints !== undefined && constraints.length > 0;
          const errCountVar = hasConstraints ? nextVar(s, 'errCount') : '';
          if (hasConstraints) {
            push(s, 0, `${errCountVar} = len(${errorsVar})`);
          }

          const allowAdditional = node.additionalProperties ?? true;
          const knownKeys = Object.keys(node.properties);

          for (const key of knownKeys) {
            const child = node.properties[key]!;
            const childPath = nextVar(s, 'p');
            push(s, 0, `${childPath} = ${pathVar} + [${pyString(key)}]`);
            const childVal = nextVar(s, 'v');
            push(s, 0, `${childVal} = ${valueExpr}.get(${pyString(key)}, _MISSING)`);
            emitNode(s, child, childVal, childPath, errorsVar, 0);
          }

          if (!allowAdditional) {
            const knownList = knownKeys.map((k) => pyString(k)).join(', ');
            push(s, 0, `for _k in sorted(${valueExpr}.keys()):`);
            push(s, 1, `if _k not in (${knownList}):`);
            push(s, 2, errLine(errorsVar, `${pathVar} + [_k]`, 'unexpected property'));
          }

          if (hasConstraints && constraints !== undefined) {
            push(s, 0, `if len(${errorsVar}) == ${errCountVar}:`);
            emitConstraints(s, constraints, valueExpr, pathVar, errorsVar, 1);
          }
        },
      );
      return;
    }

    case 'record': {
      emitGuard(
        ctx,
        depth,
        `not isinstance(${valueExpr}, dict)`,
        [errLine(errorsVar, pathVar, 'expected object')],
        (s) => {
          const keysVar = nextVar(s, '_keys');
          push(s, 0, `${keysVar} = sorted(${valueExpr}.keys())`);
          if (node.minProperties !== undefined) {
            push(s, 0, `if len(${keysVar}) < ${node.minProperties}:`);
            push(s, 1, errLine(errorsVar, pathVar, `object has fewer than ${node.minProperties} properties`));
          }
          if (node.maxProperties !== undefined) {
            push(s, 0, `if len(${keysVar}) > ${node.maxProperties}:`);
            push(s, 1, errLine(errorsVar, pathVar, `object has more than ${node.maxProperties} properties`));
          }
          const rk = nextVar(s, 'rk');
          push(s, 0, `for ${rk} in ${keysVar}:`);
          const rp = nextVar(s, 'p');
          push(s, 1, `${rp} = ${pathVar} + [${rk}]`);
          const rv = nextVar(s, 'v');
          push(s, 1, `${rv} = ${valueExpr}[${rk}]`);
          emitNode(s, node.values, rv, rp, errorsVar, 1);
        },
      );
      return;
    }

    case 'tuple': {
      emitGuard(
        ctx,
        depth,
        `not isinstance(${valueExpr}, list)`,
        [errLine(errorsVar, pathVar, 'expected array')],
        (s) => {
          emitGuard(
            s,
            0,
            `len(${valueExpr}) != ${node.items.length}`,
            [errLine(errorsVar, pathVar, `tuple must have exactly ${node.items.length} items`)],
            (s2) => {
              node.items.forEach((item, i) => {
                const tp = nextVar(s2, 'p');
                push(s2, 0, `${tp} = ${pathVar} + [${i}]`);
                const tv = nextVar(s2, 'v');
                push(s2, 0, `${tv} = ${valueExpr}[${i}]`);
                emitNode(s2, item, tv, tp, errorsVar, 0);
              });
            },
          );
        },
      );
      return;
    }

    case 'union': {
      // Each variant is emitted as an ISOLATED helper function so that one
      // variant cannot affect another.
      const variantNames: string[] = [];
      for (const variant of node.variants) {
        const name = `_union_variant_${ctx.varCounter.n}`;
        ctx.varCounter.n += 1;
        const inner: Ctx = { lines: [], varCounter: ctx.varCounter, helpers: ctx.helpers };
        emitNode(inner, variant, 'value', 'path', 'errors', 1);
        ctx.helpers.push(
          `def ${name}(value: Any, path: List[Union[str, int]], errors: List[ValidationError]) -> None:\n` +
            inner.lines.join('\n'),
        );
        variantNames.push(name);
      }

      const okVar = nextVar(ctx, 'ok');
      push(ctx, depth, `${okVar} = False`);
      for (const name of variantNames) {
        const errsVar = nextVar(ctx, 'e');
        push(ctx, depth, `if not ${okVar}:`);
        push(ctx, depth + 1, `${errsVar}: List[ValidationError] = []`);
        push(ctx, depth + 1, `${name}(${valueExpr}, ${pathVar}, ${errsVar})`);
        push(ctx, depth + 1, `if not ${errsVar}:`);
        push(ctx, depth + 2, `${okVar} = True`);
      }
      push(ctx, depth, `if not ${okVar}:`);
      push(ctx, depth + 1, errLine(errorsVar, pathVar, 'value matched no union variant'));
      return;
    }

    default: {
      const _never: never = node;
      void _never;
    }
  }
}

function emitConstraints(
  ctx: Ctx,
  constraints: ReadonlyArray<CrossFieldConstraint>,
  objVar: string,
  pathVar: string,
  errorsVar: string,
  depth: number,
): void {
  for (const c of constraints) {
    if (c.kind === 'requiredTogether') {
      const fields = c.fields;
      const msg = c.message ?? `fields must be provided together: ${fields.join(', ')}`;
      const presentVar = nextVar(ctx, 'present');
      push(ctx, depth, `${presentVar} = 0`);
      for (const f of fields) {
        push(ctx, depth, `if ${objVar}.get(${pyString(f)}, _MISSING) is not _MISSING:`);
        push(ctx, depth + 1, `${presentVar} += 1`);
      }
      push(ctx, depth, `if 0 < ${presentVar} < ${fields.length}:`);
      push(ctx, depth + 1, errLine(errorsVar, pathVar, msg));
      continue;
    }

    const msg = c.message ?? `constraint failed: ${c.left} ${comparisonText(c.kind)} ${c.right}`;
    const lv = nextVar(ctx, 'l');
    const rv = nextVar(ctx, 'r');
    push(ctx, depth, `${lv} = ${objVar}.get(${pyString(c.left)}, _MISSING)`);
    push(ctx, depth, `${rv} = ${objVar}.get(${pyString(c.right)}, _MISSING)`);
    push(ctx, depth, `if ${lv} is not _MISSING and ${rv} is not _MISSING:`);
    if (c.kind === 'equal') {
      push(ctx, depth + 1, `if not _eq_strict(${lv}, ${rv}):`);
      push(ctx, depth + 2, errLine(errorsVar, pathVar, msg));
    } else if (c.kind === 'notEqual') {
      push(ctx, depth + 1, `if _eq_strict(${lv}, ${rv}):`);
      push(ctx, depth + 2, errLine(errorsVar, pathVar, msg));
    } else {
      // Ordering constraints only apply when BOTH sides are finite numbers.
      // This mirrors the TypeScript generator and prevents Python's
      // `TypeError` on mixed types from surfacing as a parity difference.
      const op = comparisonText(c.kind);
      push(ctx, depth + 1, `if _is_number(${lv}) and _is_number(${rv}) and not (${lv} ${op} ${rv}):`);
      push(ctx, depth + 2, errLine(errorsVar, pathVar, msg));
    }
  }
}

function comparisonText(kind: Exclude<CrossFieldConstraint['kind'], 'requiredTogether'>): string {
  switch (kind) {
    case 'greaterThan':
      return '>';
    case 'lessThan':
      return '<';
    case 'greaterOrEqual':
      return '>=';
    case 'lessOrEqual':
      return '<=';
    case 'equal':
      return '==';
    case 'notEqual':
      return '!=';
  }
}

function emitFormatCheck(
  ctx: Ctx,
  format: StringFormat,
  valueExpr: string,
  pathVar: string,
  errorsVar: string,
  depth: number,
): void {
  const re = nextVar(ctx, 'fmt');
  // The shared source uses ECMA-262 syntax; translate `$` to `\Z` so a
  // trailing newline is rejected exactly like the TypeScript validator.
  push(ctx, depth, `${re} = re.compile(r'${translatePatternForPython(FORMAT_PATTERNS[format])}')`);
  push(ctx, depth, `if not ${re}.search(${valueExpr}):`);
  push(ctx, depth + 1, errLine(errorsVar, pathVar, `string does not match format ${format}`));
}
