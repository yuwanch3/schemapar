/**
 * schemapar — Python validator codegen
 *
 * Mirror of gen-ts.ts. Error messages and path shapes MUST be byte-identical
 * to the TypeScript output, otherwise parity testing is meaningless.
 *
 * Parity notes baked into the generated code:
 *  - `bool` is a subclass of `int` in Python, so integer/number checks
 *    explicitly reject booleans.
 *  - `True == 1` in Python but `true !== 1` in JS, so enum and literal
 *    comparisons are type-aware.
 *  - String length is measured in Unicode code points (Python `len()`).
 *    The TS generator is required to match this using `[...s].length`.
 *  - `optional` at the top level uses a `_MISSING` sentinel because JSON
 *    has no `undefined`; the parity harness unwraps it.
 *
 * Control-flow note: child nodes are validated inside `if / else` branches
 * rather than with early `return`s. A `return` would leave the enclosing
 * `_walk()` call entirely, silently skipping sibling properties and the rest
 * of an array. Guards therefore only skip the node they belong to.
 */

import type { SchemaNode, CrossFieldConstraint } from './schema.js';
import { translatePatternForPython, FORMAT_PATTERNS } from './schema.js';
import type { StringFormat } from './schema.js';

export interface GenPyOptions {
  /** Name of the exported validator function. Default: `validate`. */
  readonly functionName?: string;
  /** Add a header comment. Default: true. */
  readonly header?: boolean;
}

interface Ctx {
  readonly lines: string[];
  readonly varCounter: { n: number };
  /**
   * Module-level helper functions collected while emitting. Union variants
   * live here so that one variant cannot affect another.
   */
  readonly helpers: string[];
}

const INDENT = '    ';

function push(ctx: Ctx, depth: number, line: string): void {
  ctx.lines.push(INDENT.repeat(depth) + line);
}

function nextVar(ctx: Ctx, prefix: string): string {
  ctx.varCounter.n += 1;
  return `${prefix}${ctx.varCounter.n}`;
}

/** Python string literal, single-quoted, escaping backslashes and quotes. */
function pyString(s: string): string {
  const escaped = s.replace(/\\/g, '\\\\').replace(/'/g, "\\'").replace(/\n/g, '\\n');
  return `'${escaped}'`;
}

function pyValueLiteral(value: string | number | boolean | null): string {
  if (value === null) return 'None';
  if (typeof value === 'string') return pyString(value);
  if (typeof value === 'boolean') return value ? 'True' : 'False';
  return String(value);
}

/** Path list literal, e.g. `['a', 0, 'b']`. */
function pathLiteral(parts: ReadonlyArray<string | number>): string {
  const items = parts.map((p) => (typeof p === 'number' ? String(p) : pyString(p)));
  return `[${items.join(', ')}]`;
}

/**
 * The error message for a literal is baked at generation time so that TS and
 * Python emit the exact same string. Mirrors `JSON.stringify` in gen-ts.
 */
function literalMessage(value: string | number | boolean | null): string {
  return `expected literal ${JSON.stringify(value)}`;
}

export function generatePython(root: SchemaNode, options: GenPyOptions = {}): string {
  const fn = options.functionName ?? 'validate';
  const header = options.header ?? true;

  const ctx: Ctx = { lines: [], varCounter: { n: 0 }, helpers: [] };

  if (header) {
    ctx.lines.push('"""');
    ctx.lines.push('AUTO-GENERATED by schemapar. Do not edit by hand.');
    ctx.lines.push('Run `schemapar compile <schema> --target py` to regenerate.');
    ctx.lines.push('"""');
    ctx.lines.push('');
  }

  ctx.lines.push('from __future__ import annotations');
  ctx.lines.push('');
  ctx.lines.push('import math');
  ctx.lines.push('import re');
  ctx.lines.push('from typing import Any, Dict, List, Union');
  ctx.lines.push('');
  ctx.lines.push('ValidationError = Dict[str, Any]');
  ctx.lines.push('');
  ctx.lines.push('# Sentinel for an absent value, since JSON has no `undefined`.');
  ctx.lines.push('_MISSING = object()');
  ctx.lines.push('');
  ctx.lines.push('');
  ctx.lines.push('def _is_number(v: Any) -> bool:');
  ctx.lines.push('    # bool is a subclass of int in Python; JSON booleans are not numbers.');
  ctx.lines.push('    if isinstance(v, bool):');
  ctx.lines.push('        return False');
  ctx.lines.push('    if isinstance(v, int):');
  ctx.lines.push('        return True');
  ctx.lines.push('    if isinstance(v, float):');
  ctx.lines.push('        return math.isfinite(v)');
  ctx.lines.push('    return False');
  ctx.lines.push('');
  ctx.lines.push('');
  ctx.lines.push('def _is_integer(v: Any) -> bool:');
  ctx.lines.push('    if isinstance(v, bool):');
  ctx.lines.push('        return False');
  ctx.lines.push('    return isinstance(v, int)');
  ctx.lines.push('');
  ctx.lines.push('');
  ctx.lines.push('def _eq_strict(a: Any, b: Any) -> bool:');
  ctx.lines.push('    # Mirror JavaScript `===` semantics for JSON scalars, so that');
  ctx.lines.push('    # Python\'s `True == 1` and `1 == 1.0` do not cause silent parity drift.');
  ctx.lines.push('    if isinstance(a, bool) or isinstance(b, bool):');
  ctx.lines.push('        return isinstance(a, bool) and isinstance(b, bool) and a == b');
  ctx.lines.push('    if isinstance(a, (int, float)) and isinstance(b, (int, float)):');
  ctx.lines.push('        return a == b');
  ctx.lines.push('    if isinstance(a, str) and isinstance(b, str):');
  ctx.lines.push('        return a == b');
  ctx.lines.push('    return a is b');
  ctx.lines.push('');
  ctx.lines.push('');
  ctx.lines.push(`def ${fn}(value: Any) -> List[ValidationError]:`);
  push(ctx, 1, 'errors: List[ValidationError] = []');
  push(ctx, 1, '_walk(value, [], errors)');
  push(ctx, 1, 'return errors');
  ctx.lines.push('');
  ctx.lines.push('');

  ctx.lines.push('def _walk(value: Any, path: List[Union[str, int]], errors: List[ValidationError]) -> None:');
  emitNode(ctx, root, 'value', 'path', 'errors', 1);
  ctx.lines.push('');

  for (const h of ctx.helpers) {
    ctx.lines.push('');
    ctx.lines.push(h);
    ctx.lines.push('');
  }

  return ctx.lines.join('\n');
}

// ---------------------------------------------------------------------------
// Scoped emission helpers
// ---------------------------------------------------------------------------

/** Emit into a fresh relative-depth buffer so it can be nested/indented. */
function capture(ctx: Ctx, body: (sub: Ctx) => void): string[] {
  const sub: Ctx = { lines: [], varCounter: ctx.varCounter, helpers: ctx.helpers };
  body(sub);
  return sub.lines;
}

function emitLines(ctx: Ctx, depth: number, lines: ReadonlyArray<string>): void {
  for (const line of lines) ctx.lines.push(INDENT.repeat(depth) + line);
}

/**
 * `if failCond: failLines ... else: body`
 *
 * The `else` branch is omitted when the node has no further checks, and the
 * whole construct is skipped when there is nothing to do either way.
 */
function emitGuard(
  ctx: Ctx,
  depth: number,
  failCond: string,
  failLines: ReadonlyArray<string>,
  body?: (sub: Ctx) => void,
): void {
  const bodyLines = body === undefined ? [] : capture(ctx, body);
  if (bodyLines.length === 0 && failLines.length === 0) return;
  push(ctx, depth, `if ${failCond}:`);
  emitLines(ctx, depth + 1, failLines);
  if (bodyLines.length === 0) return;
  push(ctx, depth, 'else:');
  emitLines(ctx, depth + 1, bodyLines);
}

/**
 * `if not (skipCond): body`
 *
 * Used for `optional` / `nullable`: when the sentinel is present the node is
 * skipped, but the enclosing walk (siblings, arrays) continues.
 */
function emitSkip(ctx: Ctx, depth: number, skipCond: string, body: (sub: Ctx) => void): void {
  const bodyLines = capture(ctx, body);
  if (bodyLines.length === 0) return;
  push(ctx, depth, `if not (${skipCond}):`);
  emitLines(ctx, depth + 1, bodyLines);
}

function errLine(errorsVar: string, pathVar: string, message: string): string {
  return `${errorsVar}.append({'path': ${pathVar}, 'message': ${pyString(message)}})`;
}

