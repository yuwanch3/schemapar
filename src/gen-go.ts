/**
 * schemapar — Go validator codegen
 *
 * Mirror of gen-ts.ts and gen-py.ts. Generates a self-contained,
 * zero-dependency Go source file exporting `Validate(value any) []ValidationError`.
 *
 * Parity notes baked into the generated code:
 *  - Numbers from `encoding/json` are `float64`; integer checks also accept Go
 *    integer types and reject booleans (Go has no bool/number overlap, but
 *    accepting both keeps direct callers working).
 *  - Strings are measured in Unicode code points via `utf8.RuneCountInString`,
 *    matching Python `len()` and the TS `[...s].length`.
 *  - `optional` uses a `Missing` sentinel because JSON has no `undefined`.
 *  - Errors accumulate: guards use `if` / `else` instead of `return`, so a
 *    failing property does not abort its siblings.
 *  - Property and record-key iteration is deterministic. Known properties use
 *    the schema's insertion order; unknown/record keys are sorted with
 *    `sort.Strings`, which compares UTF-8 bytes (equivalent to code points).
 */

import type { SchemaNode, CrossFieldConstraint } from './schema.js';
import { translatePatternForGo, FORMAT_PATTERNS } from './schema.js';
import type { StringFormat } from './schema.js';

export interface GenGoOptions {
  /** Go package name. Default: `validator`. */
  readonly packageName?: string;
  /** Name of the exported validator function. Default: `Validate`. */
  readonly functionName?: string;
  /** Add a header comment. Default: true. */
  readonly header?: boolean;
}

interface Flags {
  regexp: boolean;
  sort: boolean;
  utf8: boolean;
}

interface Ctx {
  readonly lines: string[];
  readonly varCounter: { n: number };
  readonly helpers: string[];
  readonly flags: Flags;
}

const INDENT = '\t';

function push(ctx: Ctx, depth: number, line: string): void {
  ctx.lines.push(INDENT.repeat(depth) + line);
}

function nextVar(ctx: Ctx, prefix: string): string {
  ctx.varCounter.n += 1;
  return `${prefix}${ctx.varCounter.n}`;
}

/** Go string literal. JSON escapes (`\n`, `\uXXXX`, `\"`) are valid in Go. */
function goString(s: string): string {
  return JSON.stringify(s);
}

function goScalarLiteral(value: string | number | boolean | null): string {
  if (value === null) return 'nil';
  if (typeof value === 'string') return goString(value);
  if (typeof value === 'boolean') return value ? 'true' : 'false';
  return formatNumber(value);
}

/** Numeric literal that stays a valid Go expression for integers and floats. */
function formatNumber(n: number): string {
  if (Number.isInteger(n)) return `${n}.0`;
  return String(n);
}

export function generateGo(root: SchemaNode, options: GenGoOptions = {}): string {
  const pkg = options.packageName ?? 'validator';
  const fn = options.functionName ?? 'Validate';
  const header = options.header ?? true;

  const flags: Flags = { regexp: false, sort: false, utf8: false };
  const body: Ctx = { lines: [], varCounter: { n: 0 }, helpers: [], flags };

  emitNode(body, root, 'value', 'path', 'errors', 1);

  const lines: string[] = [];
  if (header) {
    lines.push('// Code generated by schemapar. DO NOT EDIT.');
    lines.push('// Run `schemapar compile <schema> --target go` to regenerate.');
    lines.push('');
  }
  lines.push(`package ${pkg}`);
  lines.push('');

  const imports: string[] = ['"math"'];
  if (flags.regexp) imports.push('"regexp"');
  if (flags.sort) imports.push('"sort"');
  if (flags.utf8) imports.push('"unicode/utf8"');
  if (imports.length === 1) {
    lines.push(`import ${imports[0]}`);
  } else {
    lines.push('import (');
    for (const imp of imports) lines.push(`\t${imp}`);
    lines.push(')');
  }
  lines.push('');

  pushLines(lines, [
    'type ValidationError struct {',
    '\tPath    []any  `json:"path"`',
    '\tMessage string `json:"message"`',
    '}',
    '',
    '// Missing marks an absent optional property, mirroring JS `undefined`.',
    'type missingSentinel struct{}',
    '',
    'var Missing any = missingSentinel{}',
    '',
    'func _isMissing(v any) bool {',
    '\t_, ok := v.(missingSentinel)',
    '\treturn ok',
    '}',
    '',
    'func _get(obj map[string]any, key string) any {',
    '\tif v, ok := obj[key]; ok {',
    '\t\treturn v',
    '\t}',
    '\treturn Missing',
    '}',
    '',
    'func _appendPath(path []any, elem any) []any {',
    '\tnext := make([]any, len(path)+1)',
    '\tcopy(next, path)',
    '\tnext[len(path)] = elem',
    '\treturn next',
    '}',
    '',
    'func _toFloat64(v any) (float64, bool) {',
    '\tvar f float64',
    '\tswitch n := v.(type) {',
    '\tcase float64:',
    '\t\tf = n',
    '\tcase float32:',
    '\t\tf = float64(n)',
    '\tcase int:',
    '\t\tf = float64(n)',
    '\tcase int8:',
    '\t\tf = float64(n)',
    '\tcase int16:',
    '\t\tf = float64(n)',
    '\tcase int32:',
    '\t\tf = float64(n)',
    '\tcase int64:',
    '\t\tf = float64(n)',
    '\tcase uint:',
    '\t\tf = float64(n)',
    '\tcase uint8:',
    '\t\tf = float64(n)',
    '\tcase uint16:',
    '\t\tf = float64(n)',
    '\tcase uint32:',
    '\t\tf = float64(n)',
    '\tcase uint64:',
    '\t\tf = float64(n)',
    '\tdefault:',
    '\t\treturn 0, false',
    '\t}',
    '\tif math.IsNaN(f) || math.IsInf(f, 0) {',
    '\t\treturn 0, false',
    '\t}',
    '\treturn f, true',
    '}',
    '',
    'func _isInteger(v any) bool {',
    '\tswitch n := v.(type) {',
    '\tcase int, int8, int16, int32, int64, uint, uint8, uint16, uint32, uint64:',
    '\t\treturn true',
    '\tcase float64:',
    '\t\treturn !math.IsNaN(n) && !math.IsInf(n, 0) && math.Trunc(n) == n',
    '\tcase float32:',
    '\t\tf := float64(n)',
    '\t\treturn !math.IsNaN(f) && !math.IsInf(f, 0) && math.Trunc(f) == f',
    '\tdefault:',
    '\t\treturn false',
    '\t}',
    '}',
    '',
    'func _strictEqual(a any, b any) bool {',
    '\tif a == nil || b == nil {',
    '\t\treturn a == nil && b == nil',
    '\t}',
    '\tif ab, ok := a.(bool); ok {',
    '\t\tbb, ok2 := b.(bool)',
    '\t\treturn ok2 && ab == bb',
    '\t}',
    '\tif af, ok := _toFloat64(a); ok {',
    '\t\tbf, ok2 := _toFloat64(b)',
    '\t\treturn ok2 && af == bf',
    '\t}',
    '\tif as, ok := a.(string); ok {',
    '\t\tbs, ok2 := b.(string)',
    '\t\treturn ok2 && as == bs',
    '\t}',
    '\treturn false',
    '}',
    '',
    `func ${fn}(value any) []ValidationError {`,
    '\terrors := []ValidationError{}',
    '\t_walk(value, []any{}, &errors)',
    '\treturn errors',
    '}',
    '',
    'func _walk(value any, path []any, errors *[]ValidationError) {',
  ]);
  lines.push(...body.lines);
  lines.push('}');

  for (const helper of body.helpers) {
    lines.push('');
    lines.push(helper);
  }

  lines.push('');
  return lines.join('\n');
}

function pushLines(out: string[], lines: ReadonlyArray<string>): void {
  for (const line of lines) out.push(line);
}

// ---------------------------------------------------------------------------
// Scoped emission helpers
// ---------------------------------------------------------------------------

function capture(ctx: Ctx, body: (sub: Ctx) => void): string[] {
  const sub: Ctx = { lines: [], varCounter: ctx.varCounter, helpers: ctx.helpers, flags: ctx.flags };
  body(sub);
  return sub.lines;
}

function emitLines(ctx: Ctx, depth: number, lines: ReadonlyArray<string>): void {
  for (const line of lines) ctx.lines.push(INDENT.repeat(depth) + line);
}

function emitGuard(
  ctx: Ctx,
  depth: number,
  failCond: string,
  failLines: ReadonlyArray<string>,
  body?: (sub: Ctx) => void,
): void {
  const bodyLines = body === undefined ? [] : capture(ctx, body);
  if (bodyLines.length === 0 && failLines.length === 0) return;
  push(ctx, depth, `if ${failCond} {`);
  emitLines(ctx, depth + 1, failLines);
  if (bodyLines.length === 0) {
    push(ctx, depth, '}');
    return;
  }
  push(ctx, depth, '} else {');
  emitLines(ctx, depth + 1, bodyLines);
  push(ctx, depth, '}');
}

function emitSkip(ctx: Ctx, depth: number, skipCond: string, body: (sub: Ctx) => void): void {
  const bodyLines = capture(ctx, body);
  if (bodyLines.length === 0) return;
  push(ctx, depth, `if !(${skipCond}) {`);
  emitLines(ctx, depth + 1, bodyLines);
  push(ctx, depth, '}');
}

/**
 * `if v, ok := value.(T); !ok { fail } else { body }`
 *
 * When `body` is absent the binding is discarded, which avoids Go's
 * "declared and not used" error for nodes with no constraints.
 */
function emitAssertGuard(
  ctx: Ctx,
  depth: number,
  valueExpr: string,
  goType: string,
  bindVar: string | null,
  failLines: ReadonlyArray<string>,
  body?: (sub: Ctx) => void,
): void {
  const okVar = nextVar(ctx, 'ok');
  const binding = bindVar ?? '_';
  push(ctx, depth, `if ${binding}, ${okVar} := ${valueExpr}.(${goType}); !${okVar} {`);
  emitLines(ctx, depth + 1, failLines);
  if (body === undefined) {
    push(ctx, depth, '}');
    return;
  }
  const bodyLines = capture(ctx, body);
  if (bodyLines.length === 0) {
    push(ctx, depth, '}');
    return;
  }
  push(ctx, depth, '} else {');
  emitLines(ctx, depth + 1, bodyLines);
  push(ctx, depth, '}');
}

function errLine(errorsVar: string, pathVar: string, message: string): string {
  return `*${errorsVar} = append(*${errorsVar}, ValidationError{Path: ${pathVar}, Message: ${goString(message)}})`;
}

/**
 * `if v, ok := call(); !ok { fail } else { body }`
 *
 * Used for `_toFloat64`, which returns (value, ok) rather than performing a
 * type assertion.
 */
function emitCallGuard(
  ctx: Ctx,
  depth: number,
  bindVar: string,
  callExpr: string,
  failLines: ReadonlyArray<string>,
  body?: (sub: Ctx) => void,
): void {
  const okVar = nextVar(ctx, 'ok');
  push(ctx, depth, `if ${bindVar}, ${okVar} := ${callExpr}; !${okVar} {`);
  emitLines(ctx, depth + 1, failLines);
  if (body === undefined) {
    push(ctx, depth, '}');
    return;
  }
  const bodyLines = capture(ctx, body);
  if (bodyLines.length === 0) {
    push(ctx, depth, '}');
    return;
  }
  push(ctx, depth, '} else {');
  emitLines(ctx, depth + 1, bodyLines);
  push(ctx, depth, '}');
}

// ---------------------------------------------------------------------------
// Node emission
// ---------------------------------------------------------------------------

function emitNode(
  ctx: Ctx,
  node: SchemaNode,
  valueExpr: string,
  pathVar: string,
  errorsVar: string,
  depth: number,
): void {
  const body = (c: Ctx, d: number): void =>
    emitNodeBody(c, node, valueExpr, pathVar, errorsVar, d);

  const afterNullable = (c: Ctx, d: number): void => {
    if (node.nullable) {
      emitSkip(c, d, `${valueExpr} == nil`, (sub) => body(sub, 0));
    } else {
      body(c, d);
    }
  };

  if (node.optional) {
    emitSkip(ctx, depth, `_isMissing(${valueExpr})`, (sub) => afterNullable(sub, 0));
  } else {
    afterNullable(ctx, depth);
  }
}

function emitNodeBody(
  ctx: Ctx,
  node: SchemaNode,
  valueExpr: string,
  pathVar: string,
  errorsVar: string,
  depth: number,
): void {
  switch (node.type) {
    case 'any': {
      if (!node.optional) {
        emitGuard(ctx, depth, `_isMissing(${valueExpr})`, [
          errLine(errorsVar, pathVar, 'expected a value, got undefined'),
        ]);
      }
      return;
    }

    case 'string': {
      const hasChecks =
        node.minLength !== undefined ||
        node.maxLength !== undefined ||
        node.pattern !== undefined ||
        node.format !== undefined;
      if (!hasChecks) {
        emitAssertGuard(ctx, depth, valueExpr, 'string', null, [
          errLine(errorsVar, pathVar, 'expected string'),
        ]);
        return;
      }
      const s = nextVar(ctx, 's');
      emitAssertGuard(
        ctx,
        depth,
        valueExpr,
        'string',
        s,
        [errLine(errorsVar, pathVar, 'expected string')],
        (sub) => {
          if (node.minLength !== undefined || node.maxLength !== undefined) {
            ctx.flags.utf8 = true;
            if (node.minLength !== undefined) {
              push(sub, 0, `if utf8.RuneCountInString(${s}) < ${node.minLength} {`);
              push(sub, 1, errLine(errorsVar, pathVar, `string shorter than ${node.minLength}`));
              push(sub, 0, '}');
            }
            if (node.maxLength !== undefined) {
              push(sub, 0, `if utf8.RuneCountInString(${s}) > ${node.maxLength} {`);
              push(sub, 1, errLine(errorsVar, pathVar, `string longer than ${node.maxLength}`));
              push(sub, 0, '}');
            }
          }
          if (node.pattern !== undefined) {
            ctx.flags.regexp = true;
            const re = nextVar(sub, 're');
            push(sub, 0, `${re} := regexp.MustCompile(${goString(translatePatternForGo(node.pattern))})`);
            push(sub, 0, `if !${re}.MatchString(${s}) {`);
            push(sub, 1, errLine(errorsVar, pathVar, 'string does not match pattern'));
            push(sub, 0, '}');
          }
          if (node.format !== undefined) {
            emitFormatCheck(sub, node.format, s, pathVar, errorsVar, 0);
          }
        },
      );
      return;
    }

    case 'number': {
      const hasRange = node.min !== undefined || node.max !== undefined;
      if (!hasRange) {
        emitCallGuard(ctx, depth, '_', `_toFloat64(${valueExpr})`, [
          errLine(errorsVar, pathVar, 'expected number'),
        ]);
        return;
      }
      const f = nextVar(ctx, 'f');
      emitCallGuard(
        ctx,
        depth,
        f,
        `_toFloat64(${valueExpr})`,
        [errLine(errorsVar, pathVar, 'expected number')],
        (sub) => {
          if (node.min !== undefined) {
            push(sub, 0, `if ${f} < ${formatNumber(node.min)} {`);
            push(sub, 1, errLine(errorsVar, pathVar, `number less than ${node.min}`));
            push(sub, 0, '}');
          }
          if (node.max !== undefined) {
            push(sub, 0, `if ${f} > ${formatNumber(node.max)} {`);
            push(sub, 1, errLine(errorsVar, pathVar, `number greater than ${node.max}`));
            push(sub, 0, '}');
          }
        },
      );
      return;
    }

    case 'integer': {
      const hasRange = node.min !== undefined || node.max !== undefined;
      if (!hasRange) {
        emitGuard(ctx, depth, `!_isInteger(${valueExpr})`, [
          errLine(errorsVar, pathVar, 'expected integer'),
        ]);
        return;
      }
      const f = nextVar(ctx, 'f');
      emitGuard(
        ctx,
        depth,
        `!_isInteger(${valueExpr})`,
        [errLine(errorsVar, pathVar, 'expected integer')],
        (sub) => {
          push(sub, 0, `${f}, _ := _toFloat64(${valueExpr})`);
          if (node.min !== undefined) {
            push(sub, 0, `if ${f} < ${formatNumber(node.min)} {`);
            push(sub, 1, errLine(errorsVar, pathVar, `integer less than ${node.min}`));
            push(sub, 0, '}');
          }
          if (node.max !== undefined) {
            push(sub, 0, `if ${f} > ${formatNumber(node.max)} {`);
            push(sub, 1, errLine(errorsVar, pathVar, `integer greater than ${node.max}`));
            push(sub, 0, '}');
          }
        },
      );
      return;
    }

    case 'boolean': {
      emitAssertGuard(ctx, depth, valueExpr, 'bool', null, [
        errLine(errorsVar, pathVar, 'expected boolean'),
      ]);
      return;
    }

    case 'literal': {
      const message = `expected literal ${JSON.stringify(node.value)}`;
      emitGuard(ctx, depth, `!_strictEqual(${valueExpr}, ${goScalarLiteral(node.value)})`, [
        errLine(errorsVar, pathVar, message),
      ]);
      return;
    }

    case 'enum': {
      const comparisons = node.values.map((v) => `_strictEqual(${valueExpr}, ${goScalarLiteral(v)})`);
      emitGuard(ctx, depth, `!(${comparisons.join(' || ')})`, [
        errLine(errorsVar, pathVar, 'value not in enum'),
      ]);
      return;
    }

    case 'array': {
      const arr = nextVar(ctx, 'arr');
      emitAssertGuard(
        ctx,
        depth,
        valueExpr,
        '[]any',
        arr,
        [errLine(errorsVar, pathVar, 'expected array')],
        (sub) => {
          if (node.minItems !== undefined) {
            push(sub, 0, `if len(${arr}) < ${node.minItems} {`);
            push(sub, 1, errLine(errorsVar, pathVar, `array shorter than ${node.minItems}`));
            push(sub, 0, '}');
          }
          if (node.maxItems !== undefined) {
            push(sub, 0, `if len(${arr}) > ${node.maxItems} {`);
            push(sub, 1, errLine(errorsVar, pathVar, `array longer than ${node.maxItems}`));
            push(sub, 0, '}');
          }
          const idx = nextVar(sub, 'i');
          push(sub, 0, `for ${idx} := 0; ${idx} < len(${arr}); ${idx}++ {`);
          const itemPath = nextVar(sub, 'p');
          push(sub, 1, `${itemPath} := _appendPath(${pathVar}, ${idx})`);
          const itemVal = nextVar(sub, 'v');
          push(sub, 1, `${itemVal} := ${arr}[${idx}]`);
          emitNode(sub, node.items, itemVal, itemPath, errorsVar, 1);
          push(sub, 0, '}');
        },
      );
      return;
    }

    case 'object': {
      const obj = nextVar(ctx, 'obj');
      emitAssertGuard(
        ctx,
        depth,
        valueExpr,
        'map[string]any',
        obj,
        [errLine(errorsVar, pathVar, 'expected object')],
        (sub) => {
          const constraints = node.constraints;
          const hasConstraints = constraints !== undefined && constraints.length > 0;
          const errCount = hasConstraints ? nextVar(sub, 'errCount') : '';
          if (hasConstraints) push(sub, 0, `${errCount} := len(*${errorsVar})`);

          const knownKeys = Object.keys(node.properties);
          for (const key of knownKeys) {
            const child = node.properties[key]!;
            const childPath = nextVar(sub, 'p');
            push(sub, 0, `${childPath} := _appendPath(${pathVar}, ${goString(key)})`);
            const childVal = nextVar(sub, 'v');
            push(sub, 0, `${childVal} := _get(${obj}, ${goString(key)})`);
            emitNode(sub, child, childVal, childPath, errorsVar, 0);
          }

          if (node.additionalProperties === false) {
            ctx.flags.sort = true;
            const keys = nextVar(sub, 'keys');
            const key = nextVar(sub, 'k');
            push(sub, 0, `${keys} := make([]string, 0, len(${obj}))`);
            push(sub, 0, `for ${key} := range ${obj} {`);
            push(sub, 1, `${keys} = append(${keys}, ${key})`);
            push(sub, 0, '}');
            push(sub, 0, `sort.Strings(${keys})`);
            push(sub, 0, `for _, ${key} := range ${keys} {`);
            push(sub, 1, `switch ${key} {`);
            if (knownKeys.length > 0) {
              push(sub, 1, `case ${knownKeys.map((k) => goString(k)).join(', ')}:`);
            }
            push(sub, 1, 'default:');
            push(sub, 2, errLine(errorsVar, `_appendPath(${pathVar}, ${key})`, 'unexpected property'));
            push(sub, 1, '}');
            push(sub, 0, '}');
          }

          if (hasConstraints && constraints !== undefined) {
            push(sub, 0, `if len(*${errorsVar}) == ${errCount} {`);
            emitConstraints(sub, constraints, obj, pathVar, errorsVar, 1);
            push(sub, 0, '}');
          }
        },
      );
      return;
    }

    case 'record': {
      const obj = nextVar(ctx, 'obj');
      emitAssertGuard(
        ctx,
        depth,
        valueExpr,
        'map[string]any',
        obj,
        [errLine(errorsVar, pathVar, 'expected object')],
        (sub) => {
          ctx.flags.sort = true;
          const keys = nextVar(sub, 'keys');
          const key = nextVar(sub, 'k');
          push(sub, 0, `${keys} := make([]string, 0, len(${obj}))`);
          push(sub, 0, `for ${key} := range ${obj} {`);
          push(sub, 1, `${keys} = append(${keys}, ${key})`);
          push(sub, 0, '}');
          push(sub, 0, `sort.Strings(${keys})`);
          if (node.minProperties !== undefined) {
            push(sub, 0, `if len(${keys}) < ${node.minProperties} {`);
            push(sub, 1, errLine(errorsVar, pathVar, `object has fewer than ${node.minProperties} properties`));
            push(sub, 0, '}');
          }
          if (node.maxProperties !== undefined) {
            push(sub, 0, `if len(${keys}) > ${node.maxProperties} {`);
            push(sub, 1, errLine(errorsVar, pathVar, `object has more than ${node.maxProperties} properties`));
            push(sub, 0, '}');
          }
          const itemPath = nextVar(sub, 'p');
          push(sub, 0, `for _, ${key} := range ${keys} {`);
          push(sub, 1, `${itemPath} := _appendPath(${pathVar}, ${key})`);
          const itemVal = nextVar(sub, 'v');
          push(sub, 1, `${itemVal} := ${obj}[${key}]`);
          emitNode(sub, node.values, itemVal, itemPath, errorsVar, 1);
          push(sub, 0, '}');
        },
      );
      return;
    }

    case 'tuple': {
      const arr = nextVar(ctx, 'arr');
      emitAssertGuard(
        ctx,
        depth,
        valueExpr,
        '[]any',
        arr,
        [errLine(errorsVar, pathVar, 'expected array')],
        (sub) => {
          emitGuard(
            sub,
            0,
            `len(${arr}) != ${node.items.length}`,
            [errLine(errorsVar, pathVar, `tuple must have exactly ${node.items.length} items`)],
            (inner) => {
              node.items.forEach((item, i) => {
                const itemPath = nextVar(inner, 'p');
                push(inner, 0, `${itemPath} := _appendPath(${pathVar}, ${i})`);
                const itemVal = nextVar(inner, 'v');
                push(inner, 0, `${itemVal} := ${arr}[${i}]`);
                emitNode(inner, item, itemVal, itemPath, errorsVar, 0);
              });
            },
          );
        },
      );
      return;
    }

    case 'union': {
      const variantNames: string[] = [];
      for (const variant of node.variants) {
        const name = `_unionVariant${ctx.varCounter.n}`;
        ctx.varCounter.n += 1;
        const inner: Ctx = {
          lines: [],
          varCounter: ctx.varCounter,
          helpers: ctx.helpers,
          flags: ctx.flags,
        };
        emitNode(inner, variant, 'value', 'path', 'errors', 1);
        ctx.helpers.push(
          `func ${name}(value any, path []any, errors *[]ValidationError) {\n` +
            inner.lines.join('\n') +
            '\n}',
        );
        variantNames.push(name);
      }

      const okVar = nextVar(ctx, 'ok');
      push(ctx, depth, `${okVar} := false`);
      for (const name of variantNames) {
        const errsVar = nextVar(ctx, 'e');
        push(ctx, depth, '{');
        push(ctx, depth + 1, `${errsVar} := []ValidationError{}`);
        push(ctx, depth + 1, `${name}(${valueExpr}, ${pathVar}, &${errsVar})`);
        push(ctx, depth + 1, `if len(${errsVar}) == 0 {`);
        push(ctx, depth + 2, `${okVar} = true`);
        push(ctx, depth + 1, '}');
        push(ctx, depth, '}');
      }
      push(ctx, depth, `if !${okVar} {`);
      push(ctx, depth + 1, errLine(errorsVar, pathVar, 'value matched no union variant'));
      push(ctx, depth, '}');
      return;
    }

    default: {
      const _never: never = node;
      void _never;
    }
  }
}

function emitConstraints(
  ctx: Ctx,
  constraints: ReadonlyArray<CrossFieldConstraint>,
  objVar: string,
  pathVar: string,
  errorsVar: string,
  depth: number,
): void {
  for (const c of constraints) {
    if (c.kind === 'requiredTogether') {
      const fields = c.fields;
      const msg = c.message ?? `fields must be provided together: ${fields.join(', ')}`;
      const present = nextVar(ctx, 'present');
      push(ctx, depth, `${present} := 0`);
      for (const f of fields) {
        push(ctx, depth, `if !_isMissing(_get(${objVar}, ${goString(f)})) {`);
        push(ctx, depth + 1, `${present}++`);
        push(ctx, depth, '}');
      }
      push(ctx, depth, `if ${present} > 0 && ${present} < ${fields.length} {`);
      push(ctx, depth + 1, errLine(errorsVar, pathVar, msg));
      push(ctx, depth, '}');
      continue;
    }

    const op = comparisonOp(c.kind);
    const msg = c.message ?? `constraint failed: ${c.left} ${op.text} ${c.right}`;
    const left = nextVar(ctx, 'l');
    const right = nextVar(ctx, 'r');
    push(ctx, depth, `${left} := _get(${objVar}, ${goString(c.left)})`);
    push(ctx, depth, `${right} := _get(${objVar}, ${goString(c.right)})`);
    push(ctx, depth, `if !_isMissing(${left}) && !_isMissing(${right}) {`);
    if (c.kind === 'equal') {
      push(ctx, depth + 1, `if !_strictEqual(${left}, ${right}) {`);
      push(ctx, depth + 2, errLine(errorsVar, pathVar, msg));
      push(ctx, depth + 1, '}');
    } else if (c.kind === 'notEqual') {
      push(ctx, depth + 1, `if _strictEqual(${left}, ${right}) {`);
      push(ctx, depth + 2, errLine(errorsVar, pathVar, msg));
      push(ctx, depth + 1, '}');
    } else {
      const lf = nextVar(ctx, 'lf');
      const rf = nextVar(ctx, 'rf');
      const lok = nextVar(ctx, 'lok');
      const rok = nextVar(ctx, 'rok');
      push(ctx, depth + 1, `if ${lf}, ${lok} := _toFloat64(${left}); ${lok} {`);
      push(ctx, depth + 2, `if ${rf}, ${rok} := _toFloat64(${right}); ${rok} {`);
      push(ctx, depth + 3, `if !(${lf} ${op.go} ${rf}) {`);
      push(ctx, depth + 4, errLine(errorsVar, pathVar, msg));
      push(ctx, depth + 3, '}');
      push(ctx, depth + 2, '}');
      push(ctx, depth + 1, '}');
    }
    push(ctx, depth, '}');
  }
}

interface ComparisonOp {
  readonly go: string;
  readonly text: string;
}

function comparisonOp(kind: Exclude<CrossFieldConstraint['kind'], 'requiredTogether'>): ComparisonOp {
  switch (kind) {
    case 'greaterThan':
      return { go: '>', text: '>' };
    case 'lessThan':
      return { go: '<', text: '<' };
    case 'greaterOrEqual':
      return { go: '>=', text: '>=' };
    case 'lessOrEqual':
      return { go: '<=', text: '<=' };
    case 'equal':
      return { go: '==', text: '==' };
    case 'notEqual':
      return { go: '!=', text: '!=' };
  }
}

function emitFormatCheck(
  ctx: Ctx,
  format: StringFormat,
  valueExpr: string,
  pathVar: string,
  errorsVar: string,
  depth: number,
): void {
  ctx.flags.regexp = true;
  const re = nextVar(ctx, 'fmt');
  const pattern = translatePatternForGo(FORMAT_PATTERNS[format]);
  push(ctx, depth, `${re} := regexp.MustCompile(${goString(pattern)})`);
  push(ctx, depth, `if !${re}.MatchString(${valueExpr}) {`);
  push(ctx, depth + 1, errLine(errorsVar, pathVar, `string does not match format ${format}`));
  push(ctx, depth, '}');
}
